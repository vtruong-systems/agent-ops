#!/usr/bin/env bash
# Render a gitignored Helm secrets overlay from helm.env.
# Does not print secret values.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck disable=SC1091
source "${ROOT}/scripts/dev-env.env"

HELM_ENV="${AGENT_OPS_HELM_ENV:-${ROOT}/helm.env}"
OUT="${ROOT}/${AGENT_OPS_SECRETS_VALUES}"

if [[ ! -f "${HELM_ENV}" ]]; then
  echo "missing ${HELM_ENV}"
  echo "copy helm.env.template to helm.env and fill values. Do not commit helm.env."
  exit 1
fi

set -a
# shellcheck disable=SC1090
source "${HELM_ENV}"
set +a

umask 077
mkdir -p "$(dirname "${OUT}")"
python3 - "${OUT}" <<'PY'
import os
import sys

out = sys.argv[1]
lines = ["# Generated by scripts/render-local-secret-values.sh. Gitignored.",
         "# Do not commit. Do not paste this file into chat.",
         "secrets:"]
wrote = False
for env_name, yaml_key in (
    ("OPENAI_API_KEY", "openaiApiKey"),
    ("AZURE_OPENAI_API_KEY", "azureOpenAiApiKey"),
):
    val = os.environ.get(env_name, "").strip()
    if not val:
        continue
    escaped = val.replace("\\", "\\\\").replace('"', '\\"')
    lines.append(f'  {yaml_key}: "{escaped}"')
    wrote = True
if not wrote:
    raise SystemExit("no secret keys found in helm.env")
with open(out, "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
print(f"wrote {out} (values not printed)")
PY
chmod 600 "${OUT}"
